"""Job-scoped file staging for the lr-ops bridge.

Why this module exists
----------------------
Three of the thirteen bridge commands take *filesystem paths* -- ``import_photo``,
``import_photos`` and ``export_preview``. Until now the caller (the workbench)
computed those paths on its own disk. That only worked because the workbench and
Lightroom were assumed to share a machine, and therefore a disk: on the wire the
bridge never moved bytes, it moved path *strings*.

This module moves the decision back to the bridge. The bridge owns a staging
directory on the machine where Lightroom runs, hands the plugin real local
paths, and serves the resulting bytes over HTTP to whoever asked. Callers now
refer to work by *name* (a staging id or a job id), never by path, so they no
longer need to share a disk with Lightroom.

Layout::

    <staging root>/<stage_id>/input/     files uploaded by the caller, to import
    <staging root>/<job_id>/output/      files produced by the plugin, to collect

Two identifiers, deliberately:

* **stage_id** -- generated by the bridge when the caller uploads bytes, before
  any job exists. Input files must exist before the job that consumes them.
* **job_id**   -- generated by the job queue at submit time. Output files cannot
  exist before then, so ``GET /files/<job_id>/output`` is naturally keyed by job.

Nothing here decides *what* to render or *how*; it only decides where bytes live.
The command semantics (which paths get injected, and the invariants that must
still hold) live in :func:`inject_dispatch` and :func:`collect_output`.
"""

from __future__ import annotations

import re
import shutil
import time
import uuid
from pathlib import Path
from .sidecar import SIDECAR_COMMANDS

# Commands whose params carry a caller-supplied path today. Each is replaced by a
# bridge-resolved path at dispatch time. Keys are the *caller-facing* handle; the
# value is the *plugin-facing* param name the path is written into.
INPUT_HANDLES = {
    "import_photo": ("stage_id", "path"),
    "import_photos": ("stage_ids", "paths"),
}

# Commands that produce a file on the Lightroom machine. The bridge validates
# the reported path and exposes the bytes through the same output_ref contract;
# callers never need a shared filesystem.
OUTPUT_COMMANDS = ("export_preview", "request_jpeg_thumbnail")

# One queue item carrying many plugin commands. Defined here because staging
# recurses into batch payloads at dispatch time; server.py imports it.
BATCH_COMMAND = "command_batch"

_ID_RE = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")

# How long an abandoned staging directory may linger before pruning.
DEFAULT_MAX_AGE_SEC = 6 * 60 * 60


class StagingError(RuntimeError):
    pass


def new_stage_id() -> str:
    return str(uuid.uuid4())


def _valid_id(value: object) -> str:
    """Staging ids reach this module from HTTP, so they are validated, not trusted.

    Both identifiers are server-generated UUIDs; anything else is rejected before
    it can be turned into a path. This is what keeps ``../`` out of the staging
    root, and it mirrors how ``Studio.valid_id`` guards episode directories.
    """
    if not isinstance(value, str) or not _ID_RE.match(value):
        raise StagingError(f"invalid staging id: {value!r}")
    return value


class Staging:
    """Owns the bridge's staging area. One instance per server."""

    def __init__(self, root: Path, max_age_sec: int = DEFAULT_MAX_AGE_SEC):
        self.root = Path(root)
        self.max_age_sec = max_age_sec
        self.root.mkdir(parents=True, exist_ok=True)

    # ---- paths -------------------------------------------------------------

    def _dir(self, ident: str, kind: str) -> Path:
        return self.root / _valid_id(ident) / kind

    def input_dir(self, stage_id: str) -> Path:
        return self._dir(stage_id, "input")

    def output_dir(self, job_id: str) -> Path:
        return self._dir(job_id, "output")

    def prepare_output(self, job_id: str) -> Path:
        """Create the output directory a plugin should write into."""
        path = self.output_dir(job_id)
        path.mkdir(parents=True, exist_ok=True)
        return path

    # ---- input (caller -> bridge) -----------------------------------------

    def create_stage(self) -> str:
        stage_id = new_stage_id()
        (self.root / stage_id / "input").mkdir(parents=True, exist_ok=True)
        (self.root / stage_id / ".created").write_text(str(time.time()), encoding="utf-8")
        return stage_id

    def put_input(self, stage_id: str, filename: str, data: bytes) -> Path:
        """Store one uploaded file under a stage.

        The filename is sanitised to a bare name: the caller's original name is
        preserved for the plugin's benefit (Lightroom derives the photo name from
        it) but can never escape the stage directory.
        """
        safe = Path(filename or "upload").name
        if not safe or safe in (".", ".."):
            safe = "upload"
        directory = self.input_dir(stage_id)
        directory.mkdir(parents=True, exist_ok=True)
        target = directory / safe
        target.write_bytes(data)
        return target

    def resolve_input(self, stage_id: str, filename: str | None = None) -> Path:
        """Return the on-disk path for a staged input file.

        With ``filename`` omitted the stage must hold exactly one file -- the
        common case (one photo per stage). Ambiguity is an error rather than an
        arbitrary pick, so a caller that uploaded two files without naming them
        gets told, not silently given one of them.
        """
        directory = self.input_dir(stage_id)
        if filename is None:
            candidates = sorted(p for p in directory.glob("*") if p.is_file())
            if not candidates:
                raise StagingError(f"no staged input for {stage_id}")
            if len(candidates) > 1:
                raise StagingError(
                    f"staged input {stage_id} holds {len(candidates)} files; "
                    "name the one you meant"
                )
            return candidates[0]
        safe = Path(filename).name
        target = (directory / safe).resolve()
        if target.parent != directory.resolve() or not target.is_file():
            raise StagingError(f"no staged input {filename!r} for {stage_id}")
        return target

    # ---- output (bridge -> caller) ----------------------------------------

    def collect_output(self, job_id: str) -> list[Path]:
        """List what the plugin actually wrote for a job."""
        directory = self.output_dir(job_id)
        if not directory.is_dir():
            return []
        return sorted(p for p in directory.iterdir() if p.is_file())

    def verify_output(self, job_id: str, reported_path: object) -> Path:
        """Check the plugin wrote where it was told to, and return that path.

        This is the invariant the workbench used to enforce itself::

            source = Path(data['output_path']).resolve()
            if source.parent != scratch.resolve():
                raise ValueError('Unexpected LR export path or color space')

        It has to move here for the split to be honest. The workbench no longer
        knows -- and must not assume -- where Lightroom's disk keeps this job's
        files; only the bridge knows. Leaving the check on the workbench would
        turn a real guarantee into a vacuous one: the workbench would be
        asserting something about a filesystem it cannot see.

        Keeping it means a plugin that writes outside the job's directory is
        caught loudly rather than silently served as if it were the render.
        """
        directory = self.output_dir(job_id).resolve()
        if not isinstance(reported_path, str) or not reported_path:
            raise StagingError("job reported no output path")
        actual = Path(reported_path).resolve()
        if actual.parent != directory:
            raise StagingError(
                f"LR wrote outside the staged output directory: {actual}"
            )
        if not actual.is_file():
            raise StagingError(f"LR reported {actual} but it does not exist")
        return actual

    def read_output(self, job_id: str) -> tuple[str, bytes]:
        """Return ``(filename, bytes)`` for a job's produced artifact.

        Exactly one artifact is expected. Lightroom names exports after the
        photo rather than after our id (see Commands.lua ``export_preview``), so
        the caller cannot predict the name -- that is precisely why it asks for
        "the output of job X" and lets the bridge answer.
        """
        files = self.collect_output(job_id)
        if not files:
            raise StagingError(f"job {job_id} produced no output")
        if len(files) > 1:
            raise StagingError(
                f"job {job_id} produced {len(files)} files; expected one"
            )
        return files[0].name, files[0].read_bytes()

    # ---- dispatch/collect hooks -------------------------------------------

    def inject_dispatch(self, command: str, params: dict, job_id: str) -> dict:
        """Rewrite caller handles into bridge-resolved paths, at dispatch time.

        This is the heart of the split: the caller says *what* it wants imported;
        the bridge decides *where that file is*. Runs after the job is dequeued
        and before the plugin sees it.

        ``export_preview`` is handled here too -- it gets an ``output_dir`` the
        bridge chose, replacing the caller-supplied one.

        A ``command_batch`` recurses into every entry, so a staged handle
        inside a batch resolves exactly as it would as a standalone job.
        """
        if command == BATCH_COMMAND:
            resolved = dict(params)
            entries = resolved.get("commands") or []
            resolved["commands"] = [
                {**entry, "params": self.inject_dispatch(
                    entry.get("command"), entry.get("params") or {}, job_id)}
                if isinstance(entry, dict) else entry
                for entry in entries
            ]
            return resolved
        resolved = dict(params)
        if command in SIDECAR_COMMANDS:
            # New Lua must not send private Catalog-resolved paths to a service
            # that lacks sidecar finalization/redaction support.
            resolved["_sidecar_protocol"] = 1
        if command in INPUT_HANDLES:
            handle_key, param_key = INPUT_HANDLES[command]
            handle = resolved.pop(handle_key, None)
            if handle is None:
                raise StagingError(f"{command} requires {handle_key}")
            if isinstance(handle, list):  # import_photos
                resolved[param_key] = [str(self.resolve_input(h)) for h in handle]
            else:
                name = resolved.pop("stage_name", None)
                resolved[param_key] = str(self.resolve_input(handle, name))
        if command in OUTPUT_COMMANDS:
            # Overwrite any caller-supplied path: the bridge owns this now, which
            # is what makes the shared-disk assumption unnecessary.
            resolved.pop("output_dir", None)
            resolved["output_dir"] = str(self.prepare_output(job_id))
        return resolved

    # ---- lifecycle ---------------------------------------------------------

    def discard_input(self, stage_id: str) -> None:
        shutil.rmtree(self.root / _valid_id(stage_id), ignore_errors=True)

    def discard_output(self, job_id: str) -> None:
        shutil.rmtree(self.root / _valid_id(job_id), ignore_errors=True)

    def prune(self, now: float | None = None) -> int:
        """Delete staging directories older than ``max_age_sec``.

        Called opportunistically; failures are the caller's to swallow. Abandoned
        uploads are the expected garbage -- a caller that uploads and then never
        submits a job leaves a stage behind.
        """
        now = time.time() if now is None else now
        removed = 0
        for entry in self.root.iterdir():
            if not entry.is_dir():
                continue
            try:
                age = now - entry.stat().st_mtime
            except OSError:
                continue
            if age > self.max_age_sec:
                shutil.rmtree(entry, ignore_errors=True)
                removed += 1
        return removed
